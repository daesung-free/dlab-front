/* 학번 표기 — 2026-10-13 채번이 바뀐다(피드백 1-1).
 *
 * ★ **접수·가입만으로는 학번이 나오지 않는다.** 반 배정 시점에 **반별 4자리**로 발급된다.
 *   그 전까지 서버는 `studentNo` 를 `null` 로 준다.
 *
 * ★ 그래서 `'-'` 로 그리면 안 된다. 이 레포에서 `'-'` 는 **「값이 정말 없다」**는 뜻인데
 *   (미배정 학생의 좌석처럼), 학번은 **「아직 안 매겨졌다」**다 — 곧 생긴다. 담당자가
 *   `'-'` 를 보면 **등록이 잘못된 줄 알고 다시 접수**한다. 그게 중복 데이터가 되는 길이다.
 */
export const NO_STUDENT_NO = '미배정'

/** 표에 그릴 학번. 없으면 「미배정」 — 반 배정 때 생긴다 */
export function studentNoText(v: string | null | undefined): string {
  return v && v.trim() !== '' ? v : NO_STUDENT_NO
}
